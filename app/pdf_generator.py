class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw total page count
    and clean header/footer rules on every page."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(TEXT_MUTED)

        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(0.85 * inch, 10.45 * inch, "YOUTUBE KNOWLEDGE DIGEST — EXECUTIVE REPORT")
            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.5)
            self.line(0.85 * inch, 10.35 * inch, 7.65 * inch, 10.35 * inch)

        # Footer (all pages)
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(7.65 * inch, 0.45 * inch, page_str)
        self.drawString(0.85 * inch, 0.45 * inch, "Generated by AI PDF Knowledge Engine")
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.5)
        self.line(0.85 * inch, 0.6 * inch, 7.65 * inch, 0.6 * inch)

        self.restoreState()


