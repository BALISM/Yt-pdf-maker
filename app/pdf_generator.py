def _toc_entry_style(styles):
    return ParagraphStyle(
        "TOCEntry",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=TEXT_DARK,
    )


def _escape(text: str) -> str:
    if not text:
        return ""
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


CATEGORY_BADGES = {
    "lecture": "🎓 ACADEMIC LECTURE STUDY NOTES",
    "sports": "⚽ SPORTS MATCH RECAP & HIGHLIGHTS",
    "movie": "🎬 FILM REVIEW & PLOT DIGEST",
    "tutorial": "💻 TECHNICAL TUTORIAL & CODING GUIDE",
    "business": "📊 EXECUTIVE BUSINESS BRIEF",
    "podcast": "🎙️ PODCAST & INTERVIEW HIGHLIGHTS",
    "auto": "✦ AI VIDEO INTELLIGENCE DIGEST",
}


def generate_pdf(
    summary: VideoSummary,
    output_path: Path | str,
    source_url: str | None = None,
) -> Path:
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    styles = _build_styles()
    story = []

    include_toc = len(summary.sections) >= TOC_MIN_SECTIONS

    # --- Category Pill Badge ----------------------------------------------
    cat_key = (summary.category or "auto").lower()
    badge_label = CATEGORY_BADGES.get(cat_key, CATEGORY_BADGES["auto"])
    badge_style = ParagraphStyle(
        "CategoryBadge",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        textColor=ACCENT_COLOR,
        spaceAfter=6,
    )
    story.append(Paragraph(badge_label, badge_style))

    # --- Document Header Box / Title --------------------------------------
    story.append(Paragraph(_escape(summary.title), styles["DocTitle"]))
    if summary.tagline:
        story.append(Paragraph(_escape(summary.tagline), styles["DocTagline"]))

    meta_parts = []
    if summary.estimated_read_time:
        meta_parts.append(f"⏱ Read Time: {_escape(summary.estimated_read_time)}")
    if source_url:
        meta_parts.append(f"🔗 Source: <a href='{_escape(source_url)}' color='#4338CA'><u>{_escape(source_url)}</u></a>")
    meta_parts.append(f"📅 Generated: {datetime.datetime.now().strftime('%b %d, %Y')}")
    story.append(Paragraph(" &nbsp;|&nbsp; ".join(meta_parts), styles["MetaLine"]))

    story.append(HRFlowable(width="100%", thickness=1, color=ACCENT_COLOR, spaceBefore=0, spaceAfter=14))

    # --- Executive Summary Box --------------------------------------------
    if summary.overview:
        story.append(Paragraph("Executive Summary", styles["SectionHeader"]))
        overview_p = Paragraph(_escape(summary.overview), styles["ExecutiveOverview"])
        overview_table = Table(
            [[overview_p]],
            colWidths=[6.8 * inch],
        )
        overview_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), ACCENT_LIGHT),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#C7D2FE")),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ])
        )
        story.append(overview_table)
        story.append(Spacer(1, 10))

    # --- Key Takeaways Box -----------------------------------------------
    if summary.key_takeaways:
        story.append(Paragraph("Key Takeaways", styles["SectionHeader"]))
        items = [
            ListItem(Paragraph(_escape(point), styles["TakeawayItem"]), leftIndent=12)
            for point in summary.key_takeaways
        ]
        story.append(
            ListFlowable(items, bulletType="bullet", start="circle", leftIndent=8)
        )
        story.append(Spacer(1, 12))

    # --- Table of Contents ------------------------------------------------
    if include_toc:
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=6, spaceAfter=10))
        story.append(Paragraph("Table of Contents", styles["TOCHeading"]))
        toc = TableOfContents()
        toc.levelStyles = [_toc_entry_style(styles)]
        story.append(toc)
        story.append(Spacer(1, 14))

    # --- Sections --------------------------------------------------------
    if summary.sections:
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=6, spaceAfter=10))
        story.append(Paragraph("Detailed Analysis & Key Concepts", styles["SectionHeader"]))
        story.append(Spacer(1, 6))

    for i, section in enumerate(summary.sections):
        sec_elements = []
        heading_text = _escape(section.heading)
        timestamp_str = f" [{_escape(section.timestamp)}]" if section.timestamp else ""
        
        full_heading = f"{i+1}. {heading_text}{timestamp_str}"
        para = Paragraph(f'<a name="section-{i}"/>{full_heading}', styles["SubSectionHeader"])
        para._toc_text = f"{i+1}. {heading_text}"
        para._toc_level = 0
        sec_elements.append(para)

        if section.bullets:
            items = [
                ListItem(Paragraph(_escape(b), styles["BulletText"]), leftIndent=12)
                for b in section.bullets
            ]
            sec_elements.append(
                ListFlowable(items, bulletType="bullet", start="disc", leftIndent=8)
            )

        if section.detail:
            sec_elements.append(Paragraph(_escape(section.detail), styles["DetailText"]))

        if section.key_quote:
            quote_p = Paragraph(f'“{_escape(section.key_quote)}”', styles["QuoteText"])
            quote_table = Table([[quote_p]], colWidths=[6.6 * inch])
            quote_table.setStyle(
                TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                    ("TOPPADDING", (0, 0), (-1, -1), 6),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ("LINELEFT", (0, 0), (0, -1), 3, ACCENT_COLOR),
                ])
            )
            sec_elements.append(Spacer(1, 4))
            sec_elements.append(quote_table)

        if section.actionable_tips:
            sec_elements.append(Spacer(1, 4))
            tip_items = [
                ListItem(Paragraph(f"<b>Actionable:</b> {_escape(tip)}", styles["TipText"]), leftIndent=12)
                for tip in section.actionable_tips
            ]
            sec_elements.append(
                ListFlowable(tip_items, bulletType="bullet", start="square", leftIndent=8)
            )

        sec_elements.append(Spacer(1, 8))
        story.append(KeepTogether(sec_elements))

    # --- Key Terminology / Glossary --------------------------------------
    if summary.key_terms:
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=10, spaceAfter=10))
        term_elements = [Paragraph("Key Terminology & Concepts", styles["SectionHeader"])]
        table_data = []
        for kt in summary.key_terms:
            t_cell = Paragraph(_escape(kt.term), styles["TermName"])
            d_cell = Paragraph(_escape(kt.definition), styles["TermDef"])
            table_data.append([t_cell, d_cell])

        terms_table = Table(table_data, colWidths=[2.2 * inch, 4.6 * inch])
        terms_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ])
        )
        term_elements.append(terms_table)
        term_elements.append(Spacer(1, 10))
        story.append(KeepTogether(term_elements))

    # --- Deep Dive Q&A Section --------------------------------------------
    if summary.deep_dive_qa:
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=10, spaceAfter=10))
        qa_elements = [Paragraph("Deep Dive Q&A", styles["SectionHeader"])]
        for i, qa in enumerate(summary.deep_dive_qa):
            q_p = Paragraph(f"Q{i+1}: {_escape(qa.question)}", styles["QAQuestion"])
            a_p = Paragraph(f"A: {_escape(qa.answer)}", styles["QAAnswer"])
            qa_elements.extend([q_p, a_p])
        qa_elements.append(Spacer(1, 10))
        story.append(KeepTogether(qa_elements))

    # --- Conclusion Box ---------------------------------------------------
    if summary.conclusion:
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceBefore=10, spaceAfter=10))
        conc_elements = [Paragraph("Conclusion & Synthesis", styles["SectionHeader"])]
        conc_p = Paragraph(_escape(summary.conclusion), styles["ExecutiveOverview"])
        conc_table = Table([[conc_p]], colWidths=[6.8 * inch])
        conc_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F0FDF4")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#BBF7D0")),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ])
        )
        conc_elements.append(conc_table)
        story.append(KeepTogether(conc_elements))

    doc = _TOCDocTemplate(
        str(output_path),
        pagesize=LETTER,
        leftMargin=0.85 * inch,
        rightMargin=0.85 * inch,
        topMargin=0.85 * inch,
        bottomMargin=0.85 * inch,
        title=summary.title,
    )

    if include_toc:
        doc.multiBuild(story, canvasmaker=NumberedCanvas)
    else:
        doc.build(story, canvasmaker=NumberedCanvas)

    return output_path


class _TOCDocTemplate(BaseDocTemplate):
    def __init__(self, filename, **kwargs):
        super().__init__(filename, **kwargs)
        frame = Frame(
            self.leftMargin,
            self.bottomMargin,
            self.width,
            self.height,
            id="normal",
        )
        self.addPageTemplates([PageTemplate(id="main", frames=frame)])

    def afterFlowable(self, flowable):
        if hasattr(flowable, "_toc_text"):
            self.notify(
                "TOCEntry",
                (flowable._toc_level, flowable._toc_text, self.page),
            )

